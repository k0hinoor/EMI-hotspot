/**
 * Demo Mode data source (PRD §12.7).
 *
 * This is the ONLY module in the application that produces synthetic readings.
 * Everything it creates is flagged `is_demo: true`, carries the device id
 * `DEMO-000`, is excluded from the real history on load, and is deleted when
 * demo mode is left. It exists so the interface can be inspected without a
 * detector attached — never to stand in for hardware.
 */

import type { AcquisitionMetadata, Measurement, ProbeType, QualityStatus, Scan } from './types'

export const DEMO_DEVICE_ID = 'DEMO-000'
export const DEMO_PREFIX = 'DEMO'

/** Deterministic PRNG so the demo field looks the same on every run. */
function mulberry32(seed: number) {
  let a = seed
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

interface FieldSpec {
  width: number
  height: number
  spacing: number
  /** Hotspot centres in mm and their strength. */
  hotspots: { x: number; y: number; amp: number; sigma: number }[]
  base: number
  seed: number
}

function gauss(x: number, y: number, hx: number, hy: number, sigma: number) {
  const d2 = (x - hx) ** 2 + (y - hy) ** 2
  return Math.exp(-d2 / (2 * sigma * sigma))
}

/** Synthetic field strength at a point — smooth hotspots plus a little noise. */
export function demoFieldAt(spec: FieldSpec, x: number, y: number, jitter = 1): number {
  const rand = mulberry32(Math.round(x * 131 + y * 977 + spec.seed))
  let value = spec.base
  for (const h of spec.hotspots) value += h.amp * gauss(x, y, h.x, h.y, h.sigma)
  // Mild board-edge rolloff, as a real probe sees when it leaves the DUT.
  const edge = Math.min(x, spec.width - x) / (spec.width * 0.18)
  const edgeY = Math.min(y, spec.height - y) / (spec.height * 0.18)
  value *= Math.min(1, 0.72 + 0.28 * Math.min(1, edge) * Math.min(1, edgeY))
  value += (rand() - 0.5) * 90 * jitter
  return Math.max(0, Math.round(value))
}

