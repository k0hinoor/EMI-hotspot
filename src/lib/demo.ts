function acquisitionMetadata(
  probeType: ProbeType,
  adcMax: number,
  processed: number | null,
  state: QualityStatus | null,
  supersededBy: string | null,
): AcquisitionMetadata {
  return {
    probe_type: probeType,
    sample_count: 32,
    adc_max: adcMax,
    averaging_window: 32,
    firmware_signal_state: state ?? 'VALID',
    baseline_value: 340,
    gain_setting: 1,
    processed_source: processed !== null ? 'FIRMWARE' : 'NONE',
    superseded_by: supersededBy,
  }
}

interface BuildOptions {
  adcMax: number
  saturatedAt: number
  unit: string
  startedAt?: number
}

/**
 * Builds a complete demo scan: a realistic partial coverage pattern, a quality
 * mix, and a few re-measured cells so the supersede flow is visible too.
 */
export function buildDemoScan(
  spec: FieldSpec,
  probe: { probe_id: string; probe_type: ProbeType; label: string },
  index: number,
  options: BuildOptions,
): { scan: Scan; measurements: Measurement[] } {
  const { adcMax, saturatedAt, unit } = options
  const rand = mulberry32(spec.seed + index * 31)
  const started = options.startedAt ?? Date.now() - (index === 0 ? 13 : 26) * 60_000
  const cols = Math.round(spec.width / spec.spacing)
  const rows = Math.round(spec.height / spec.spacing)

  const scanId = `${DEMO_PREFIX}-SCAN-${index + 1}`
  const scan: Scan = {
    scan_id: scanId,
    scan_name: index === 0 ? 'Demo · buck converter top side' : 'Demo · buck converter (H-field)',
    board_width_mm: spec.width,
    board_height_mm: spec.height,
    grid_spacing_mm: spec.spacing,
    probe_id: probe.probe_id,
    probe_type: probe.probe_type,
    started_at: new Date(started).toISOString(),
    completed_at: index === 1 ? new Date(started + 9 * 60_000).toISOString() : null,
    status: index === 1 ? 'COMPLETED' : 'ACTIVE',
    notes: 'DEMO DATA — generated by Demo Mode. Not a hardware measurement.',
    origin: 'TOP_LEFT',
    calibration_profile_id: `CAL-DEMO-${probe.probe_type === 'E_FIELD' ? 'E' : 'H'}`,
  }

  const measurements: Measurement[] = []
  let counter = 0
  const coverage = index === 0 ? 0.82 : 0.64

  for (let row = 0; row < rows; row++) {
    for (let col = 0; col < cols; col++) {
      // Leave a plausible uncovered band rather than a uniform sprinkle.
      const covered = rand() < coverage && !(col === cols - 1 && rand() < 0.6)
      if (!covered) continue

      const x = +(spec.spacing * (col + 0.5)).toFixed(1)
      const y = +(spec.spacing * (row + 0.5)).toFixed(1)
      const raw = demoFieldAt(spec, x, y)
      const roll = rand()

      let quality: QualityStatus = 'VALID'
      if (raw >= saturatedAt) quality = 'SATURATED'
      else if (roll > 0.945) quality = 'INVALID'
      else if (roll > 0.86) quality = 'UNSTABLE'

      const processed = quality === 'INVALID' ? null : Math.max(0, Math.round(raw * 0.972 + 14))
      const at = started + counter * 1900 + Math.round(rand() * 900)
      counter += 1

      measurements.push({
        measurement_id: `${DEMO_PREFIX}-S${index + 1}-RD-${String(counter).padStart(3, '0')}`,
        scan_id: scanId,
        probe_id: probe.probe_id,
        probe_type: probe.probe_type,
        x_mm: x,
        y_mm: y,
        signal_raw: raw,
        signal_processed: processed,
        unit,
        timestamp: new Date(at).toISOString(),
        quality_status: quality,
        calibration_profile_id: scan.calibration_profile_id,
        acquisition_metadata: acquisitionMetadata(probe.probe_type, adcMax, processed, quality, null),
        device_id: DEMO_DEVICE_ID,
      })
    }
  }

  // Three re-measured cells: old reading kept, marked invalid and superseded.
  const candidates = measurements.filter((m) => m.quality_status === 'VALID').slice(6, 9)
  candidates.forEach((old, i) => {
    const better = {
      ...old,
      measurement_id: `${DEMO_PREFIX}-S${index + 1}-RD-R${i + 1}`,
      signal_raw: Math.max(0, old.signal_raw + 120 + i * 40),
      timestamp: new Date(new Date(old.timestamp).getTime() + 240_000).toISOString(),
      quality_status: 'VALID' as QualityStatus,
    }
    better.signal_processed = Math.round(better.signal_raw * 0.972 + 14)
    old.quality_status = 'INVALID'
    old.acquisition_metadata = { ...old.acquisition_metadata, superseded_by: better.measurement_id }
    measurements.push(better)
  })

  return { scan, measurements }
}

export interface DemoStreamState {
  seq: number
  phase: number
}

/** One synthetic frame, emitted in the firmware's own wire format. */
export function demoTick(spec: FieldSpec, state: DemoStreamState): { line: string; next: DemoStreamState } {
  const phase = state.phase + 0.16
  const cx = spec.hotspots[0].x + Math.sin(phase) * 2.4
  const cy = spec.hotspots[0].y + Math.cos(phase * 0.8) * 1.8
  const raw = demoFieldAt(spec, cx, cy, 2.2)
  const filtered = Math.round(raw * 0.972 + 14)
  const status = raw >= 4050 ? 'SATURATED' : Math.abs(Math.sin(phase * 1.7)) > 0.985 ? 'UNSTABLE' : 'VALID'
  const line =
    `#DATA {"seq":${state.seq},"signal_raw":${raw},"signal_filtered":${filtered},` +
    `"sample_count":32,"status":"${status}","probe_type":"${spec === H_FIELD ? 'H_FIELD' : 'E_FIELD'}"}`
  return { line, next: { seq: state.seq + 1, phase } }
}

